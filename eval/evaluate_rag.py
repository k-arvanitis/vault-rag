"""Full RAG evaluation using DeepEval metrics.

Usage:
    python -m eval.evaluate_rag [--dataset eval/dataset.json] [--output eval/results.json]

What it does:
1. Loads QA pairs from eval/dataset.json (generated by eval/generate_dataset.py).
2. For each pair, runs the RAG agent and captures:
       actual_output     — the agent's final answer
       retrieval_context — the chunks the agent actually retrieved (from ToolMessages)
3. Evaluates each pair with three DeepEval metrics (threshold 0.7):
       FaithfulnessMetric         — is the answer grounded in retrieved context?
       ContextualRecallMetric     — did retrieval cover the expected answer?
       ContextualPrecisionMetric  — were retrieved chunks actually useful?
4. Saves full per-case results to eval/results.json.
5. Prints a summary table of average scores per metric.

Judge LLM: Qwen3-32B-AWQ (local vLLM) by default.
           Override with JUDGE_API_BASE / JUDGE_MODEL / JUDGE_API_KEY for CI.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

from dotenv import load_dotenv
from langchain_core.messages import AIMessage, HumanMessage, SystemMessage, ToolMessage

load_dotenv()

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATASET = REPO_ROOT / "eval" / "dataset.json"
DEFAULT_OUTPUT = REPO_ROOT / "eval" / "results.json"

METRIC_THRESHOLD = 0.7


# ---------------------------------------------------------------------------
# Agent wrapper — captures answer + retrieval context without touching src/
# ---------------------------------------------------------------------------

def _parse_retrieval_context(tool_content: str) -> list[str]:
    """Split the tool output into individual chunk strings.

    Tool format (from _fetch_docs):
        [1] file=foo.xlsx sheet=Sheet1 score=3.0508
        <content1>

        [2] file=bar.pdf chunk=0 score=2.7165
        <content2>
    """
    if not tool_content or tool_content.strip() == "No relevant information found.":
        return []
    # Split on blank lines that are immediately followed by a citation marker
    parts = re.split(r"\n\n(?=\[\d+\])", tool_content.strip())
    return [p.strip() for p in parts if p.strip()]


def run_agent(agent, query: str, system_prompt: str) -> tuple[str, list[str]]:
    """Run the agent and return (actual_output, retrieval_context).

    Mirrors ask_agent() but also extracts ToolMessage content for DeepEval.
    Retries with reduced chunk limits on context-overflow (400) errors.
    """
    from openai import BadRequestError
    from src.config import RERANK_TOP_N

    _input = {"messages": [SystemMessage(content=system_prompt), HumanMessage(content=query)]}
    _config = {"recursion_limit": 20}
    _limits: dict = getattr(agent, "_rag_limits", {})

    try:
        result = agent.invoke(_input, config=_config)
    except BadRequestError as exc:
        err_str = str(exc).lower()
        if "input tokens" in err_str or "context" in err_str or "400" in err_str:
            print(f"  [WARN] Context overflow — retrying with fewer chunks.")
            _limits["rerank_top_n"] = max(3, _limits.get("rerank_top_n", RERANK_TOP_N) // 2)
            try:
                result = agent.invoke(_input, config=_config)
            finally:
                _limits["rerank_top_n"] = RERANK_TOP_N
        else:
            raise
    messages: list = result.get("messages", [])

    # Collect all retrieved chunks from every tool call in this conversation
    retrieval_context: list[str] = []
    for msg in messages:
        if isinstance(msg, ToolMessage):
            content = msg.content if isinstance(msg.content, str) else str(msg.content)
            retrieval_context.extend(_parse_retrieval_context(content))

    # Final LLM answer (strip Qwen3 <think> tags)
    actual_output = "No answer generated."
    for msg in reversed(messages):
        if isinstance(msg, AIMessage) and not msg.tool_calls:
            text = re.sub(r"(?is)<think>.*?</think>\s*", "", str(msg.content)).strip()
            if text:
                actual_output = text
                break

    return actual_output, retrieval_context


# ---------------------------------------------------------------------------
# Evaluation
# ---------------------------------------------------------------------------

def evaluate(dataset_path: Path, output_path: Path, note: str = "") -> None:
    from deepeval.metrics import (
        ContextualPrecisionMetric,
        ContextualRecallMetric,
        FaithfulnessMetric,
    )
    from deepeval.test_case import LLMTestCase

    from eval.judge_llm import OpenAICompatibleJudge
    from src.config import (
        GENERATION_API_BASE,
        GENERATION_MODEL,
        QDRANT_COLLECTION,
        QDRANT_URL,
        RERANK_TOP_N,
        RERANKER_MODEL,
        RETRIEVAL_TOP_K,
    )
    from src.rag_agent import SYSTEM_PROMPT, build_rag_agent

    # Load dataset
    if not dataset_path.exists():
        sys.exit(f"[ERROR] Dataset not found: {dataset_path}\n       Run: python -m eval.generate_dataset")
    pairs: list[dict] = json.loads(dataset_path.read_text(encoding="utf-8"))
    print(f"Loaded {len(pairs)} QA pairs from {dataset_path}")

    # Initialise judge
    judge = OpenAICompatibleJudge()
    print(f"Judge LLM : {judge.get_model_name()}")

    # Initialise metrics (shared judge, shared threshold)
    metrics = [
        FaithfulnessMetric(threshold=METRIC_THRESHOLD, model=judge, include_reason=True),
        ContextualRecallMetric(threshold=METRIC_THRESHOLD, model=judge, include_reason=True),
        ContextualPrecisionMetric(threshold=METRIC_THRESHOLD, model=judge, include_reason=True),
    ]
    metric_names = [m.__class__.__name__ for m in metrics]

    # Build RAG agent (uses defaults from config / .env)
    print("Building RAG agent…")
    agent = build_rag_agent(
        qdrant_url=QDRANT_URL,
        collection=QDRANT_COLLECTION,
        retrieval_top_k=RETRIEVAL_TOP_K,
        rerank_top_n=RERANK_TOP_N,
        reranker_model_name=RERANKER_MODEL or None,
        model_name=GENERATION_MODEL,
        generation_api_base=GENERATION_API_BASE,
    )

    # Run evaluation
    results: list[dict] = []
    score_accum: dict[str, list[float]] = {name: [] for name in metric_names}

    for idx, pair in enumerate(pairs, start=1):
        question = pair["input"]
        expected = pair["expected_output"]
        context_gt = pair.get("context", [])

        print(f"\n[{idx}/{len(pairs)}] {question[:80]}…")

        try:
            actual_output, retrieval_context = run_agent(agent, question, SYSTEM_PROMPT)
        except Exception as exc:
            print(f"  [WARN] Agent failed: {exc}")
            actual_output = ""
            retrieval_context = []

        test_case = LLMTestCase(
            input=question,
            actual_output=actual_output,
            expected_output=expected,
            context=context_gt,
            retrieval_context=retrieval_context,
        )

        case_result: dict = {
            "input": question,
            "expected_output": expected,
            "actual_output": actual_output,
            "retrieval_context": retrieval_context,
            "metrics": {},
        }

        for metric in metrics:
            name = metric.__class__.__name__
            try:
                metric.measure(test_case)
                score = metric.score
                passed = metric.is_successful()
                reason = getattr(metric, "reason", "")
            except Exception as exc:
                score = 0.0
                passed = False
                reason = str(exc)

            case_result["metrics"][name] = {
                "score": score,
                "passed": passed,
                "reason": reason,
            }
            score_accum[name].append(score)
            status = "✓" if passed else "✗"
            print(f"  {status} {name}: {score:.3f}")

        results.append(case_result)

        # Brief pause between cases to avoid overloading local vLLM
        time.sleep(0.5)

    # Save results — rotate current → previous before overwriting
    output_path.parent.mkdir(parents=True, exist_ok=True)
    if output_path.exists():
        output_path.replace(output_path.parent / (output_path.stem + "_previous" + output_path.suffix))
    output_path.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nFull results saved → {output_path}")

    # Build summary
    summary: dict = {
        "total_pairs": len(results),
        "threshold": METRIC_THRESHOLD,
        "metrics": {},
    }
    for name in metric_names:
        scores = score_accum[name]
        if scores:
            avg = sum(scores) / len(scores)
            pass_count = sum(1 for s in scores if s >= METRIC_THRESHOLD)
            summary["metrics"][name] = {
                "avg_score": round(avg, 4),
                "pass_rate": round(pass_count / len(scores), 4),
                "passed": pass_count,
                "total": len(scores),
                "passed_threshold": avg >= METRIC_THRESHOLD,
            }

    summary_path = output_path.parent / "summary.json"
    if summary_path.exists():
        summary_path.replace(output_path.parent / "summary_previous.json")
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Summary saved       → {summary_path}")

    # Append to runs.json — persistent log of every eval run
    import subprocess, datetime
    runs_path = output_path.parent / "runs.json"
    try:
        runs = json.loads(runs_path.read_text(encoding="utf-8")) if runs_path.exists() else []
    except Exception:
        runs = []
    try:
        commit = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"],
                                         cwd=REPO_ROOT, text=True).strip()
    except Exception:
        commit = "unknown"
    runs.append({
        "id": len(runs) + 1,
        "timestamp": datetime.datetime.now().strftime("%Y-%m-%d %H:%M"),
        "commit": commit,
        "note": note,
        "dataset": str(dataset_path.relative_to(REPO_ROOT)),
        "n_pairs": len(results),
        "metrics": {
            name: round(sum(score_accum[name]) / len(score_accum[name]), 4)
            for name in metric_names if score_accum[name]
        },
    })
    runs_path.write_text(json.dumps(runs, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Run logged          → {runs_path}")

    # Summary table
    print("\n" + "=" * 60)
    print(f"{'Metric':<35} {'Avg Score':>10} {'Pass Rate':>10}")
    print("-" * 60)
    for name in metric_names:
        scores = score_accum[name]
        if scores:
            avg = sum(scores) / len(scores)
            pass_rate = sum(1 for s in scores if s >= METRIC_THRESHOLD) / len(scores)
            status = "✓" if avg >= METRIC_THRESHOLD else "✗"
            print(f"{status} {name:<33} {avg:>10.3f} {pass_rate:>9.1%}")
    print("=" * 60)


HARD_CASES_PATH = REPO_ROOT / "eval" / "hard_cases.json"

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Evaluate the RAG agent with DeepEval metrics.")
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--note", type=str, default="", help="Short description of what changed in this run.")
    parser.add_argument("--hard-cases", action="store_true",
                        help=f"Run only against hard cases from {HARD_CASES_PATH} (fast targeted check).")
    args = parser.parse_args()
    dataset = HARD_CASES_PATH if args.hard_cases else args.dataset
    output = args.output.parent / ("hard_cases_results.json" if args.hard_cases else args.output.name)
    evaluate(dataset_path=dataset, output_path=output, note=args.note)
